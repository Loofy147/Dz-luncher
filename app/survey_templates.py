def list_survey_templates() -> list[dict[str, Any]]:
    """Return display-ready template metadata without mutable payload internals."""
    fields = (
        "id",
        "name",
        "category",
        "summary",
        "decision",
        "audience",
        "duration_minutes",
        "target_completes",
        "minimum_interpretable_n",
        "customization_required",
        "fieldwork_protocol",
        "quota_guidance",
        "launch_checks",
    )
    return [{field: deepcopy(template[field]) for field in fields} for template in _TEMPLATES]


def get_survey_template(template_id: str) -> dict[str, Any] | None:
    """Return one fully isolated template, or None for an unknown identifier."""
    for template in _TEMPLATES:
        if template["id"] == template_id:
            return deepcopy(template)
    return None


def template_payload(template_id: str) -> dict[str, Any] | None:
    """Return only the campaign payload that can be edited and saved as a draft."""
    template = get_survey_template(template_id)
    return template["payload"] if template else None
